-- Полная очистка платежей: входящие платежи и загруженные реестры (с самими файлами).
-- Запускается ВРУЧНУЮ, приложением не используется. Цель: загрузить ZIP с реестрами заново с чистого листа.
--
--   psql "$DATABASE_URL" -f scripts/sql/clear_payments.sql
--
-- Что удаляется физически (не «мягко»), это необратимо:
--   * incoming_payments   - все входящие платежи (из реестров и введённые вручную);
--   * payment_registries  - все загруженные реестры, включая сохранённые файлы.
-- Физическое удаление освобождает и номера операций Сбера: платежи, ранее помеченные удалёнными,
-- при мягком удалении остаются «занятыми» и блокировали бы повторную загрузку.
--
-- НЕ удаляются: банковские счета, категории платежей, лицевые счета, дома, помещения, собственники.
-- Исходящие платежи по умолчанию тоже остаются (раздел ниже закомментирован: раскомментируйте, если нужно).
--
-- Всё выполняется одной транзакцией. Чтобы только посмотреть, что будет, замените COMMIT на ROLLBACK.

BEGIN;

SELECT 'до очистки' AS этап,
       (SELECT count(*) FROM incoming_payments)  AS входящих_платежей,
       (SELECT count(*) FROM payment_registries) AS реестров,
       (SELECT count(*) FROM outgoing_payments)  AS исходящих_платежей;

-- Сначала платежи (ссылаются на реестры), потом реестры.
DELETE FROM incoming_payments;
DELETE FROM payment_registries;

-- Исходящие платежи (по умолчанию не трогаем):
-- DELETE FROM outgoing_payments;

SELECT 'после очистки' AS этап,
       (SELECT count(*) FROM incoming_payments)  AS входящих_платежей,
       (SELECT count(*) FROM payment_registries) AS реестров,
       (SELECT count(*) FROM outgoing_payments)  AS исходящих_платежей;

COMMIT;
