package sberapi

import (
	"bytes"
	"testing"
)

func TestBerToDER(t *testing.T) {
	cases := []struct {
		name     []byte
		in, want []byte
	}{
		{
			name: []byte("неопределённая длина"),
			in:   []byte{0x30, 0x80, 0x02, 0x01, 0x03, 0x00, 0x00},
			want: []byte{0x30, 0x03, 0x02, 0x01, 0x03},
		},
		{
			name: []byte("вложенная неопределённая длина"),
			in:   []byte{0x30, 0x80, 0xa0, 0x80, 0x04, 0x01, 0xff, 0x00, 0x00, 0x00, 0x00},
			want: []byte{0x30, 0x05, 0xa0, 0x03, 0x04, 0x01, 0xff},
		},
		{
			name: []byte("DER остаётся как есть"),
			in:   []byte{0x30, 0x06, 0xa0, 0x04, 0x04, 0x02, 0xaa, 0xbb},
			want: []byte{0x30, 0x06, 0xa0, 0x04, 0x04, 0x02, 0xaa, 0xbb},
		},
	}
	for _, c := range cases {
		got, err := berToDER(c.in)
		if err != nil || !bytes.Equal(got, c.want) {
			t.Errorf("%s: got %x err %v, want %x", string(c.name), got, err, c.want)
		}
	}
	for _, bad := range [][]byte{{0x30, 0x80, 0x02, 0x01, 0x03}, {0x04, 0x80, 0x00, 0x00}, {0x30, 0x05, 0x02}} {
		if _, err := berToDER(bad); err == nil {
			t.Errorf("%x: ожидалась ошибка", bad)
		}
	}
}
